     * 面板也用它决定要不要给格子画「可选肤色」角标。
     */
    private val skinToneIndex: Map<String, List<String>> by lazy {
        buildMap {
            skinToneVariants.forEach { (base, variants) ->
                put(base, variants)
                put(base.replace("\uFE0F", ""), variants)
            }
        }
    }

